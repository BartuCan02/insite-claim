# ------------------------------------------------------------------ text helpers
_LATIN1 = [("–", "-"), ("—", "-"), ("−", "-"), ("‑", "-"), ("×", "x"), ("≥", ">="),
           ("≤", "<="), ("±", "+/-"), ("€", "EUR"), ("‘", "'"), ("’", "'"), ("‚", "'"),
           ("“", '"'), ("”", '"'), ("„", '"'), ("…", "..."), ("•", "-"), ("→", "->"),
           (" ", " "), (" ", " "), (" ", " ")]


def latin1(text) -> str:
    """fpdf2 core fonts only know Latin-1: swap common typography for ASCII, drop the rest."""
    s = str(text)
    for a, b in _LATIN1:
        s = s.replace(a, b)
    return s.encode("latin-1", "ignore").decode("latin-1")


def _kwh(x: float) -> str:
    return f"{x:,.0f}"


def _rate(x: float) -> str:
    """At least 4 decimals, more when the rate has them, so 'kWh x rate = amount' adds up on paper."""
    return f"{x:.4f}" if round(x, 4) == x else f"{x:g}"


def _when(t: pd.Timestamp) -> str:
    return f"{t:%d %b %Y, %H:%M}"


def _shown_end(ctx: dict) -> pd.Timestamp:
    """ctx['end'] is the last missing 10-minute step; the outage ends 10 minutes later."""
    return pd.Timestamp(ctx["end"]) + pd.Timedelta(minutes=10)


# ------------------------------------------------------------------ PDF building blocks
class _Report(FPDF):
    def normalize_text(self, text: str) -> str:
        return super().normalize_text(latin1(text))

    def footer(self):
        self.set_y(-13)
        self.set_draw_color(*GRID)
        self.set_line_width(0.2)
        self.line(self.l_margin, self.get_y() - 2, self.w - self.r_margin, self.get_y() - 2)
        self.set_font(FONT, "", 7.5)
        self.set_text_color(*TEXT3)
        self.cell(self.epw - 22, 4, FOOTER)
        self.cell(22, 4, f"Page {self.page_no()} of {{nb}}", align="R")


def _need(pdf: FPDF, h: float):
    if pdf.get_y() + h > pdf.page_break_trigger:
        pdf.add_page()


def _h2(pdf: FPDF, text: str, need: float = 40):
    _need(pdf, need)
    pdf.ln(5)
    pdf.set_font(FONT, "B", 13)
    pdf.set_text_color(*INK)
    pdf.cell(0, 8, text, new_x="LMARGIN", new_y="NEXT")


def _p(pdf: FPDF, text: str, size: float = 9.5, color=TEXT2, style: str = ""):
    pdf.set_font(FONT, style, size)
    pdf.set_text_color(*color)
    pdf.multi_cell(0, size * 0.5, text, new_x="LMARGIN", new_y="NEXT")


def _fit(pdf: FPDF, text: str, width: float, size: float, style: str = "B", smallest: float = 9) -> float:
    while size > smallest:
        pdf.set_font(FONT, style, size)
        if pdf.get_string_width(text) <= width:
            break
        size -= 0.5
    return size


def _clip(pdf: FPDF, text: str, width: float) -> str:
    """Shorten text with '...' so it fits width in the current font (cell() does not clip)."""
    if pdf.get_string_width(text) <= width:
        return text
    while text and pdf.get_string_width(text.rstrip(" ,") + "...") > width:
        text = text[:-1]
    return text.rstrip(" ,") + "..."


def _logo(pdf: FPDF, x: float, y: float, h: float):
    """The app's turbine mark: dark tower, three blue blades. Drawn in the SVG's -20..20 x -22..24 box."""
    s = h / 46

    def pt(px, py):
        return x + (px + 20) * s, y + (py + 22) * s

    pdf.set_fill_color(*INK)
    pdf.polygon([pt(-1.4, 0), pt(-0.7, 22), pt(0.7, 22), pt(1.4, 0)], style="F")
    pdf.set_fill_color(*BLUE)
    for a in (0, 120, 240):
        c, sn = math.cos(math.radians(a)), math.sin(math.radians(a))
        blade = [(0, 0), (-1.5, -2), (0, -19), (1.5, -2)]
        pdf.polygon([pt(bx * c - by * sn, bx * sn + by * c) for bx, by in blade], style="F")
    pdf.set_fill_color(*INK)
    cx, cy = pt(0, 0)
    pdf.ellipse(cx - 2.4 * s, cy - 2.4 * s, 4.8 * s, 4.8 * s, style="F")


def _kpis(pdf: FPDF, items: list[tuple[str, str, str, str]]):
    """Grey rounded tiles: (label, value, unit, note)."""
    gap, h = 4, 25
    w = (pdf.epw - gap * (len(items) - 1)) / len(items)
    y = pdf.get_y()
    for i, (label, value, unit, note) in enumerate(items):
        x = pdf.l_margin + i * (w + gap)
        pdf.set_fill_color(*FILL)
        pdf.rect(x, y, w, h, style="F", round_corners=True, corner_radius=3)
        pdf.set_xy(x + 5, y + 4)
        pdf.set_font(FONT, "", 8)
        pdf.set_text_color(*TEXT2)
        pdf.cell(w - 10, 4, label)
        pdf.set_font(FONT, "", 9)
        unit_w = pdf.get_string_width(unit) + 1.5 if unit else 0
        _fit(pdf, value, w - 10 - unit_w, 18)
        pdf.set_xy(x + 5, y + 9)
        pdf.set_text_color(*INK)
        pdf.cell(pdf.get_string_width(value) + 1.5, 9, value)
        if unit:
            pdf.set_font(FONT, "", 9)
            pdf.set_text_color(*TEXT2)
            pdf.cell(unit_w, 9.6, unit)
        if note:
            pdf.set_xy(x + 5, y + 18.5)
            _fit(pdf, note, w - 10, 7.5, style="", smallest=6.5)
            pdf.set_text_color(*TEXT3)
            pdf.cell(w - 10, 4, _clip(pdf, note, w - 10))
    pdf.set_xy(pdf.l_margin, y + h + 2)


def _fit_first_col(pdf: FPDF, cells: list[str], widths: list[float], size: float, pad: float) -> list[float]:
    """Widen the first column (up to 30 % of the table) so names like 'WTG-01-Nordsee' stay on one line."""
    pdf.set_font(FONT, "B", size)
    total = sum(widths)
    need = min((max((pdf.get_string_width(c) for c in cells), default=0) + 2 * pad + 0.5) / pdf.epw, 0.3) * total
    if need <= widths[0]:
        return widths
    rest = total - widths[0]
    return [need] + [w - (need - widths[0]) * w / rest for w in widths[1:]]


def _table(pdf: FPDF, header: list[str], rows: list[list[str]], widths: list[float], align: list[str],
           bold_last: bool = False, size: float = 9):
    widths = _fit_first_col(pdf, [r[0] for r in rows], widths, size, pad=1.6)
    pdf.set_font(FONT, "", size)
    pdf.set_text_color(*INK)
    pdf.set_draw_color(*LINE)
    pdf.set_fill_color(255, 255, 255)
    pdf.set_line_width(0.25)
    head = FontFace(family=FONT, emphasis="BOLD", size_pt=7.5, color=TEXT2)
    bold = FontFace(family=FONT, emphasis="BOLD", size_pt=size, color=INK)
    with pdf.table(col_widths=widths, text_align=align, borders_layout="HORIZONTAL_LINES", headings_style=head,
                   line_height=size * 0.48, padding=(1.9, 1.6), width=pdf.epw, v_align="MIDDLE") as t:
        t.row(header)
        for i, cells in enumerate(rows):
            style = bold if bold_last and i == len(rows) - 1 else None
            r = t.row()
            for c in cells:
                r.cell(c, style=style)
    pdf.ln(1)


# ------------------------------------------------------------------ charts (matplotlib, PNG in memory)
_RC = {"font.family": "sans-serif", "font.sans-serif": ["Helvetica Neue", "Helvetica", "Arial", "DejaVu Sans"],
       "font.size": 7.5, "axes.edgecolor": "#d2d2d7", "axes.linewidth": 0.6, "axes.labelcolor": "#6e6e73",
       "xtick.color": "#6e6e73", "ytick.color": "#6e6e73", "xtick.major.size": 0, "ytick.major.size": 0,
       "xtick.major.pad": 4, "ytick.major.pad": 4, "axes.spines.top": False, "axes.spines.right": False,
       "legend.frameon": False, "svg.fonttype": "none"}


def _png(draw, w_mm: float, h_mm: float) -> io.BytesIO:
    with matplotlib.rc_context(_RC):
        fig = Figure(figsize=(w_mm / 25.4, h_mm / 25.4), dpi=220, layout="constrained")
        ax = fig.add_subplot()
        draw(ax)
        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=220, facecolor="white")
    buf.seek(0)
    return buf


def _legend_cols(names: list[str], width_mm: float = 160, font_pt: float = 7.5) -> int:
    """Legend columns that fit the chart width: handle + gap + text (about 0.6 em per character)."""
    em = font_pt * 25.4 / 72
    entry = (1.6 + 0.8 + 2.0 + 0.6 * max((len(n) for n in names), default=1)) * em
    return max(1, min(len(names), int(width_mm // entry)))


def _wind_chart(results) -> io.BytesIO:
    def draw(ax):
        for i, r in enumerate(results):
            ax.plot(pd.DatetimeIndex(r["timestamps"]), r["wind_pred"], color=SERIES[i % len(SERIES)], lw=1.3,
                    solid_joinstyle="round", solid_capstyle="round", label=r["target"])
        ax.grid(axis="y", color="#e8e8ed", lw=0.6)
        ax.spines["left"].set_visible(False)
        ax.set_ylabel("Rebuilt wind speed (m/s)")
        ax.set_ylim(bottom=0)
        ax.xaxis.set_major_locator(mdates.DayLocator())
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%d %b"))
        ax.margins(x=0.01)
        ax.legend(loc="lower left", bbox_to_anchor=(0, 1.0), ncol=_legend_cols([r["target"] for r in results]),
                  handlelength=1.6, fontsize=7.5,
                  labelcolor="#1d1d1f", borderaxespad=0.2)

    return _png(draw, 174, 66)


def _energy_chart(results) -> io.BytesIO:
    def draw(ax):
        names = [r["target"] for r in results]
        e = np.array([r["energy_kwh"] for r in results]) / 1000
        lo = np.array([r["range_kwh"][0] for r in results]) / 1000
        hi = np.array([r["range_kwh"][1] for r in results]) / 1000
        y = np.arange(len(results))
        ax.barh(y, e, height=0.36, color=[SERIES[i % len(SERIES)] for i in range(len(results))], zorder=2)
        ax.errorbar(e, y, xerr=[e - lo, hi - e], fmt="none", ecolor="#6e6e73", elinewidth=0.9, capsize=3.5,
                    capthick=0.9, zorder=3)
        for yi, v, a, b in zip(y, e, lo, hi):
            ax.text(b + hi.max() * 0.02, yi, f"{v:,.1f} MWh  ({a:,.1f} - {b:,.1f})", va="center", ha="left",
                    color="#1d1d1f", fontsize=7.5)
        ax.set_yticks(y, names)
        ax.invert_yaxis()
        ax.set_xlim(0, hi.max() * 1.42)
        ax.grid(axis="x", color="#e8e8ed", lw=0.6, zorder=0)
        ax.spines["left"].set_visible(False)
        ax.spines["bottom"].set_visible(False)
        ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:,.0f}"))
        ax.set_xlabel("Lost energy (MWh), whiskers show the range")

    return _png(draw, 174, _energy_chart_h(results))


def _energy_chart_h(results) -> float:
    return 20 + 9 * len(results)


# ------------------------------------------------------------------ contract rows
def _contract_rows(contract, calc: dict, results, level: str) -> list[list[str]]:
    T = contract.terms
    rows = []

    def row(key, rule, applied):
        t = T.get(key)
        rows.append([t.clause if t is not None and t.clause else "-", rule, applied])

    def val(key):
        if calc.get(key) is not None:
            return calc[key]
        t = T.get(key)
        return t.value if t is not None else None

    n_refs = sorted({len(r["refs"]) for r in results})
    refs_txt = f"{n_refs[0]} reference turbines per turbine" if len(n_refs) == 1 else "Reference turbines per turbine"
    row("cover", "Interruption events are covered", "Communication loss; the turbines could not feed in")
    row("method", "Lost energy from reference turbines and power curves", f"{refs_txt}, turbines' own power curves")
    waiting = val("waiting_h")
    if waiting or (T.get("waiting_h") is not None and T["waiting_h"].clause):
        applied = (f"{_kwh(calc['waiting_kwh'])} kWh deducted, {_kwh(calc['claimable_kwh'])} kWh claimable"
                   if "waiting_kwh" in calc else "-")
        row("waiting_h", f"Waiting period {float(waiting):g} h", applied)
    rate = val("rate")
    rate = rate if rate is not None else val("rate_eur_kwh")
    if rate:
        applied = (f"{_kwh(calc['claimable_kwh'])} kWh x EUR {_rate(rate)} = EUR {calc['claimable_kwh'] * rate:,.2f}"
                   if "claimable_kwh" in calc else "-")
        row("rate_eur_kwh", f"EUR {_rate(rate)} per kWh", applied)
    cap = val("cap")
    cap = cap if cap is not None else val("cap_eur")
    if cap:
        applied = "-" if "capped" not in calc else ("Capped at the limit" if calc["capped"] else "Within the limit")
        row("cap_eur", f"Limit EUR {cap:,.0f} per event", applied)
    row("validation", "Method and uncertainty documented and validated", f"{N_SIM_OUTAGES} simulated outages, {level} % range")
    row("resolution", "10-minute time series", "Provided as CSV in the evidence package")
    notice = val("notice_days")
    if notice:
        applied = f"By {calc['notify_by']:%d %B %Y}" if calc.get("notify_by") is not None else "-"
        row("notice_days", f"Notify within {float(notice):.0f} days", applied)
    pay = val("payment_days")
    if pay:
        row("payment_days", f"Payment within {float(pay):.0f} days", "After receipt of the complete documentation")
    return rows


# ------------------------------------------------------------------ 1) PDF report
def report_pdf(results, ctx, contract, calc, level, park_name, insurer, policy, window_days, w_lin, w_lgbm, travel) -> bytes:
    """A 2-3 page A4 claim report: figures, per-turbine table, charts, accuracy, contract basis, method."""
    level = str(level)
    start, end = pd.Timestamp(ctx["start"]), _shown_end(ctx)
    pdf = _Report(format="A4", unit="mm")
    pdf.set_margins(18, 16, 18)
    pdf.set_auto_page_break(True, margin=20)
    pdf.set_title(latin1(f"Energy yield loss report - {park_name}"))
    pdf.set_author(APP_NAME)
    pdf.set_creator(APP_NAME)
    pdf.add_page()

    # brand + title
    _logo(pdf, pdf.l_margin, pdf.get_y(), 7)
    pdf.set_xy(pdf.l_margin + 7.5, pdf.get_y() + 0.6)
    pdf.set_font(FONT, "B", 11)
    pdf.set_text_color(*INK)
    pdf.cell(60, 6, APP_NAME)
    pdf.set_font(FONT, "", 8.5)
    pdf.set_text_color(*TEXT3)
    pdf.cell(0, 6, "Claim report", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(9)
    pdf.set_font(FONT, "B", 25)
    pdf.set_text_color(*INK)
    pdf.cell(0, 11, "Energy yield loss report", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1.5)
    _p(pdf, f"{park_name} · communication outage from {_when(start)} to {_when(end)} ({ctx['hours']:.0f} hours)",
       size=11, color=TEXT2)
    extra = [x for x in (f"Prepared for {insurer}" if insurer else "", f"Policy {policy}" if policy else "") if x]
    if extra:
        pdf.ln(0.5)
        _p(pdf, " · ".join(extra), size=9, color=TEXT3)
    pdf.ln(6)

    # KPI tiles
    targets = [r["target"] for r in results]
    _kpis(pdf, [
        ("Estimated energy loss", _kwh(ctx["total"]), "kWh", f"{ctx['total'] / 1000:,.1f} MWh over {ctx['hours']:.0f} hours"),
        (f"{level} % range", f"{_kwh(ctx['lo'])} - {_kwh(ctx['hi'])}", "kWh", f"From {N_SIM_OUTAGES} simulated 3-day outages"),
        ("Affected turbines", str(len(results)), "", ", ".join(targets)),
    ])

    # per turbine
    _h2(pdf, "Per turbine", need=20 + 8 * len(results))
    rows = [[r["target"], f"{float(np.nanmean(r['wind_pred'])):.1f} m/s", _kwh(r["energy_kwh"]),
             f"{_kwh(r['range_kwh'][0])} - {_kwh(r['range_kwh'][1])}", ", ".join(r["refs"])] for r in results]
    if len(results) > 1:
        rows.append(["Park", "", _kwh(ctx["total"]), f"{_kwh(ctx['lo'])} - {_kwh(ctx['hi'])}", ""])
    _table(pdf, ["Turbine", "Mean rebuilt wind", "Lost energy (kWh)", f"{level} % range (kWh)", "Reference turbines"],
           rows, [13, 17, 18, 22, 30], ["LEFT", "RIGHT", "RIGHT", "RIGHT", "LEFT"], bold_last=len(results) > 1)
    if len(results) > 1:
        _p(pdf, "The park range is narrower than the sum of the turbine ranges because errors of single turbines partly cancel.",
           size=8, color=TEXT3)

    # charts
    _h2(pdf, "Rebuilt wind during the outage", need=82)
    _p(pdf, "10-minute wind speed of each affected turbine, rebuilt from the reference parks.", size=9)
    pdf.ln(1)
    pdf.image(_wind_chart(results), x=pdf.l_margin, w=pdf.epw, h=66)
    h2 = _energy_chart_h(results)
    _h2(pdf, "Lost energy per turbine", need=h2 + 18)
    _p(pdf, f"Bars show the estimate, whiskers the {level} % range.", size=9)
    pdf.ln(1)
    pdf.image(_energy_chart(results), x=pdf.l_margin, w=pdf.epw, h=h2)

    # accuracy check
    if results and all("test_metrics" in r for r in results):
        _h2(pdf, "Accuracy check", need=36 + 8 * len(results))
        tw = ctx.get("test_window")
        if tw:
            _p(pdf, f"The same model was applied to {tw[0]:%d %b} - {tw[1]:%d %b %Y}, after the outage, where the turbines "
                    "measured again, and compared with those measurements.", size=9)
        else:
            _p(pdf, "The same model was applied to a period where the turbines measured, and compared with those measurements.", size=9)
        pdf.ln(1)
        acc = [[r["target"], f"{m['wind_rmse']:.2f}", f"{m['wind_mae']:.2f}", f"{m['power_rmse']:,.0f}", f"{m['power_mae']:,.0f}",
                f"{m['energy_dev_pct']:+.1f} %"] for r in results for m in [r["test_metrics"]]]
        _table(pdf, ["Turbine", "Wind RMSE (m/s)", "Wind MAE (m/s)", "Power RMSE (kW)", "Power MAE (kW)", "Energy deviation"],
               acc, [14, 17, 17, 17, 17, 18], ["LEFT", "RIGHT", "RIGHT", "RIGHT", "RIGHT", "RIGHT"])

    # contract basis
    if contract is not None:
        c = calc or {}
        crows = _contract_rows(contract, c, results, level)
        _h2(pdf, "Contract basis", need=40 + 7 * len(crows))
        pre = contract.preamble
        _p(pdf, " · ".join(x for x in (f"Policy {policy or pre.get('policy', '-')}", pre.get("insurer", "")) if x), size=9)
        if c.get("amount") is not None:
            pdf.ln(2)
            pdf.set_font(FONT, "B", 12)
            pdf.set_text_color(*INK)
            pdf.cell(0, 6.5, f"Claimed amount: EUR {c['amount']:,.2f}", new_x="LMARGIN", new_y="NEXT")
            _p(pdf, f"{level} % range EUR {c['amount_lo']:,.0f} - {c['amount_hi']:,.0f}"
                    f" · claimable energy {_kwh(c['claimable_kwh'])} kWh ({_kwh(c['claimable_lo'])} - {_kwh(c['claimable_hi'])} kWh)"
                    + (" · capped at the limit per event" if c.get("capped") else ""), size=9)
        elif c.get("claimable_kwh") is not None:
            pdf.ln(2)
            pdf.set_font(FONT, "B", 12)
            pdf.set_text_color(*INK)
            pdf.cell(0, 6.5, f"Claimable energy: {_kwh(c['claimable_kwh'])} kWh", new_x="LMARGIN", new_y="NEXT")
            _p(pdf, f"{level} % range {_kwh(c['claimable_lo'])} - {_kwh(c['claimable_hi'])} kWh. No compensation rate found.", size=9)
        if c.get("below_waiting"):
            _p(pdf, "The outage is shorter than the waiting period, so nothing is claimable under this contract.", size=9, color=INK)
        pdf.ln(2)
        _table(pdf, ["Clause", "Contract rule", "Applied to this claim"], crows, [12, 44, 44], ["LEFT", "LEFT", "LEFT"])

    # method
    dens = ", corrected for air density" if any(r.get("air_density") is not None for r in results) else ""
    steps = [
        f"Reference turbines in neighbouring parks were selected automatically by correlation with each affected turbine "
        f"over the {int(window_days)} days before the outage.",
        f"A blend of a linear model ({w_lin} %) and gradient-boosted trees ({w_lgbm} %) learned each affected turbine's wind "
        f"from the references' wind, time-shifted wind{', direction-dependent travel time' if travel else ''}, wind direction "
        f"and turbulence.",
        "The missing 10-minute wind speeds were rebuilt from the references, which kept measuring during the outage.",
        f"Energy was computed with the turbines' power curves, averaged over the typical wobble of real wind around the "
        f"estimate instead of read at a single point{dens}.",
        f"The {level} % range comes from back-testing the method on {N_SIM_OUTAGES} simulated 3-day outages.",
    ]
    _h2(pdf, "Method", need=60)
    for i, s in enumerate(steps, 1):
        _need(pdf, 12)
        y = pdf.get_y() + 1.2
        pdf.set_fill_color(*FILL)
        pdf.ellipse(pdf.l_margin, y, 5.4, 5.4, style="F")
        pdf.set_xy(pdf.l_margin, y + 0.2)
        pdf.set_font(FONT, "B", 8)
        pdf.set_text_color(*BLUE)
        pdf.cell(5.4, 5, str(i), align="C")
        pdf.set_xy(pdf.l_margin + 8, y)
        pdf.set_font(FONT, "", 9.5)
        pdf.set_text_color(*INK)
        pdf.multi_cell(pdf.epw - 8, 5, s, new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1.8)
    return bytes(pdf.output())


# ------------------------------------------------------------------ 3) claim calculation CSV
def calculation_csv(calc, results) -> bytes:
    """The claim arithmetic step by step: step,value,unit,basis. Rows without a value are left out."""
    rows = []

    def add(step, value, unit, basis, fmt="{:.1f}"):
        if value is None:
            return
        if isinstance(value, (bool, np.bool_)):
            v = "yes" if value else "no"
        elif isinstance(value, pd.Timestamp):
            v = f"{value:%Y-%m-%d}"
        else:
            v = fmt.format(float(value))
        rows.append([step, v, unit, basis])

    for r in results:
        add(f"Lost energy {r['target']}", r["energy_kwh"], "kWh", "Rebuilt wind through the turbine's power curve, summed over the outage")
    c = calc or {}
    total = c.get("total_kwh", sum(r["energy_kwh"] for r in results))
    add("Lost energy total", total, "kWh", "Sum over the affected turbines")
    add("Outage duration", c.get("outage_hours"), "h", "From the first missing 10-minute step to the end of the last", "{:g}")
    add("Waiting period", c.get("waiting_h"), "h", "Not indemnified, counted from the start of the outage", "{:g}")
    add("Energy in waiting period (deducted)", c.get("waiting_kwh"), "kWh", "Lost energy of each turbine during the waiting period")
    add("Claimable energy", c.get("claimable_kwh"), "kWh", "Lost energy total minus the waiting-period energy")
    add("Claimable energy (low)", c.get("claimable_lo"), "kWh", "Lower end of the uncertainty range")
    add("Claimable energy (high)", c.get("claimable_hi"), "kWh", "Upper end of the uncertainty range")
    add("Compensation rate", c.get("rate"), "EUR/kWh", "Agreed rate per kWh", "{:g}")
    capped = " and limited to the cap per event" if c.get("cap") else ""
    add("Claim amount", c.get("amount"), "EUR", f"Claimable energy x rate{capped}", "{:.2f}")
    add("Claim amount (low)", c.get("amount_lo"), "EUR", f"Claimable energy (low) x rate{capped}", "{:.2f}")
    add("Claim amount (high)", c.get("amount_hi"), "EUR", f"Claimable energy (high) x rate{capped}", "{:.2f}")
    add("Limit per event", c.get("cap"), "EUR", "Maximum indemnity per interruption event", "{:.2f}")
    add("Capped", c.get("capped"), "", "Whether the limit reduced the claim amount")
    notice = c.get("notice_days")
    add("Notify insurer by", c.get("notify_by"), "date",
        f"{float(notice):.0f} days after the outage ended" if notice else "Notification deadline")
    out = io.StringIO()
    w = csv.writer(out, lineterminator="\n")
    w.writerow(["step", "value", "unit", "basis"])
    w.writerows(rows)
    return out.getvalue().encode("utf-8")


