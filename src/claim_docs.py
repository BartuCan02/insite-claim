def evidence_zip(wide, results, ctx, calc, contract_name, contract_bytes, summary) -> bytes:
    """Everything an insurer needs to check the estimate, as real data files in one ZIP."""
    start, end = pd.Timestamp(ctx["start"]), pd.Timestamp(ctx["end"])
    t0 = wide.index[min(int(np.min(r["train_idx"])) for r in results)]
    refs = sorted({x for r in results for x in r["refs"]})
    targets = [r["target"] for r in results]
    files: dict[str, bytes] = {}

    rec = pd.concat([pd.DataFrame({"timestamp": pd.DatetimeIndex(r["timestamps"]), "turbine": r["target"],
                                   "rebuilt_wind_speed_ms": np.round(np.asarray(r["wind_pred"], float), 3),
                                   "expected_power_kw": np.round(np.asarray(r["power_kw"], float), 1),
                                   "energy_kwh": np.round(np.asarray(r["power_kw"], float) * INTERVAL_HOURS, 2)})
                     for r in results], ignore_index=True)
    files["reconstructed_wind_and_power.csv"] = _csv(rec, float_format=None)
    in_window = (wide.index >= t0) & (wide.index <= end)
    files["reference_measurements.csv"] = _csv(_measurements(wide, in_window, refs, {"wind_speed": "wind_speed_ms",
                                                                                    "wind_direction": "wind_direction_deg"}))
    before = (wide.index >= t0) & (wide.index < start)
    files["target_measurements_before_outage.csv"] = _csv(_measurements(wide, before, targets, {"wind_speed": "wind_speed_ms"}))
    pcs = pd.concat([pd.DataFrame({"turbine": r["target"], "wind_speed_ms": r["power_curve"]["wind_speed"].to_numpy(float),
                                   "power_kw": r["power_curve"]["power"].to_numpy(float)}) for r in results], ignore_index=True)
    files["power_curves.csv"] = _csv(pcs, float_format=None)

    tw = ctx.get("test_window")
    validation = {
        "note": (f"The uncertainty range comes from back-testing the method on {N_SIM_OUTAGES} simulated 3-day outages: each "
                 "3-day window was hidden and rebuilt using only the days before it, and the spread of the energy errors "
                 "gives the range. inner_metrics: each 3-day block of the training period hidden in turn and predicted by a "
                 "model fitted on the rest. test_metrics: the same model applied to a measured period after the outage. "
                 "wobble_sd: typical spread (m/s) of real wind around the estimate, used to average the power curve."),
        "training_period": {"start": t0, "end_before": start},
        "test_window": {"start": tw[0], "end": tw[1]} if tw else None,
        "turbines": {r["target"]: {**({"test_metrics": r["test_metrics"]} if "test_metrics" in r else {}),
                                   "inner_metrics": r.get("inner_metrics"), "wobble_sd": r.get("wobble_sd"),
                                   "energy_kwh": r["energy_kwh"], "range_kwh": list(r["range_kwh"]),
                                   "range_level_pct": r.get("range_level")} for r in results},
    }
    files["validation.json"] = json.dumps(_jsonable(validation), indent=2).encode("utf-8")
    incident = {"outage_start": start, "outage_end": _shown_end(ctx), "last_missing_step": end, "hours": ctx["hours"],
                "affected_turbines": targets, "references": {r["target"]: list(r["refs"]) for r in results},
                "estimated_loss_kwh": ctx.get("total"), "range_kwh": [ctx.get("lo"), ctx.get("hi")]}
    files["incident.json"] = json.dumps(_jsonable(incident), indent=2).encode("utf-8")
    if calc is not None:
        files["claim_calculation.csv"] = calculation_csv(calc, results)
    if summary is not None:
        files["summary.json"] = json.dumps(summary, indent=2, default=str).encode("utf-8")
    contract_file = None
    if contract_bytes:
        contract_file = Path(str(contract_name or "contract")).name or "contract"
        if contract_file in files or contract_file == "README.txt":
            contract_file = f"contract_{contract_file}"
        files[contract_file] = bytes(contract_bytes)
    files["README.txt"] = _readme(ctx, results, list(files), contract_file).encode("utf-8")

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for name, data in files.items():
            z.writestr(name, data)
    return buf.getvalue()
