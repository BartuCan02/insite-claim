def _jsonable(x):
    if isinstance(x, dict):
        return {str(k): _jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple, np.ndarray)):
        return [_jsonable(v) for v in x]
    if isinstance(x, (pd.Timestamp, np.datetime64)):
        return str(pd.Timestamp(x))
    if isinstance(x, (bool, np.bool_)):
        return bool(x)
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, (float, np.floating)):
        return None if not np.isfinite(x) else float(x)
    return x


def _csv(df: pd.DataFrame, float_format: str = "%.3f") -> bytes:
    return df.to_csv(index=False, float_format=float_format, date_format="%Y-%m-%d %H:%M:%S").encode("utf-8")


def _measurements(wide: pd.DataFrame, rows: pd.Series, turbines: list[str], variables: dict) -> pd.DataFrame:
    sub = wide.loc[rows]
    cols = {"timestamp": sub.index}
    for t in turbines:
        for var, suffix in variables.items():
            cols[f"{t}_{suffix}"] = sub[(var, t)].to_numpy() if (var, t) in sub.columns else np.nan
    return pd.DataFrame(cols)


